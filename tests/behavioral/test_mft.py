"""MFT (Minimum Functionality Test): obvious cases must be classified correctly.

The three demo texts from the README GIF are the same passage written by a human,
polished by an AI and generated by an AI. Each must be predicted as its own class.
"""

import pytest

pytestmark = pytest.mark.behavioral


@pytest.mark.parametrize("label", ["human", "ai_assisted", "ai_generated"])
def test_demo_text_is_predicted_as_its_own_class(detector, demo_texts, record, label):
    probs = detector.probabilities(demo_texts[label])
    predicted = max(probs, key=probs.get)
    record("MFT", f"{label} demo text", expected=label, predicted=predicted, probabilities=probs)

    assert predicted == label, f"{label} demo text predicted as {predicted}: {probs}"
